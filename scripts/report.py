"""RESULTS.md and web/public/data/dashboard.json from reports/dev.json and reports/heldout.json.

python scripts/report.py
"""

from __future__ import annotations

import json

from edd.taxonomy import ROOT

KEYS = (
    "flag_precision",
    "flag_recall",
    "risk_accuracy",
    "high_risk_recall",
    "case_correct",
    "no_draft_rate",
    "cost_per_case_usd",
    "p95_latency_ms",
)


def pick(ev: dict) -> dict:
    return {k: ev[k] for k in (*KEYS, "case_correct_ci", "high_risk_recall_ci", "failure_modes", "per_flag")}


def main() -> None:
    dev = json.loads((ROOT / "reports" / "dev.json").read_text())
    held = json.loads((ROOT / "reports" / "heldout.json").read_text())
    dash = {
        "chosen_config": dev["chosen_config"],
        "agreement": {"dev": dev["agreement"], "heldout": held["agreement"]},
        "experiments": [
            {
                "id": d["id"],
                "hypothesis": d["hypothesis"],
                "metric": d["metric"],
                "direction": d["direction"],
                "dev": {k: d[k] for k in ("effect", "ci", "p_one_sided", "confirmed", "n")},
                "heldout": {k: h[k] for k in ("effect", "ci", "p_one_sided", "confirmed", "n")},
            }
            for d, h in zip(dev["experiments"], held["experiments"])
        ],
        "heldout": {
            "baseline": pick(held["baseline"]),
            "chosen": pick(held["chosen"]),
            "without_checks": pick(held["chosen_without_checks"]),
            "lift": held["chosen_vs_baseline"],
            "checks": held["checks"],
        },
        "dev": {"baseline": pick(dev["baseline"]), "chosen": pick(dev["chosen"]), "checks": dev["checks"]},
        "production": {
            **dev["production"],
            "weeks": [
                {**w, "edit_ucl": None if w["edit_ucl"] != w["edit_ucl"] else w["edit_ucl"]}
                for w in dev["production"]["weeks"]
            ],
        },
        "deflection": dev["deflection"],
    }
    out = ROOT / "web" / "public" / "data" / "dashboard.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(dash, indent=1) + "\n")

    b, c, w = held["baseline"], held["chosen"], held["chosen_without_checks"]
    md = [
        "# Results",
        "",
        "Generated by `scripts/report.py` from `reports/*.json`. Do not edit by hand.",
        "",
        "## Held-out split (900 new cases, run once after `config/heldout.lock`)",
        "",
        f"Configuration chosen on the development split: `{json.dumps(dev['chosen_config'])}`",
        "",
        "| Metric | Baseline prompt | Chosen configuration | Chosen, without the checks |",
        "|---|---|---|---|",
    ]
    for k in KEYS:
        md.append(f"| {k} | {b[k]:.3f} | {c[k]:.3f} | {w[k]:.3f} |")
    lift = held["chosen_vs_baseline"]
    md += [
        "",
        f"Case-level accuracy lift: {lift['effect']:+.1%} (95% CI {lift['ci'][0]:+.1%} to {lift['ci'][1]:+.1%}).",
        "",
        "## Pre-registered experiments",
        "",
        "| Experiment | Metric | Dev effect (95% CI) | Held-out effect (95% CI) "
        "| Held-out one-sided p | Confirmed (Holm) |",
        "|---|---|---|---|---|---|",
    ]
    for e in dash["experiments"]:
        d, h = e["dev"], e["heldout"]
        md.append(
            f"| {e['id']} | {e['metric']} | {d['effect']:+.3f} ({d['ci'][0]:+.3f}, {d['ci'][1]:+.3f}) | "
            f"{h['effect']:+.3f} ({h['ci'][0]:+.3f}, {h['ci'][1]:+.3f}) | {h['p_one_sided']:.4f} | "
            f"{'yes' if h['confirmed'] else 'no'} |"
        )
    a = held["agreement"]
    md += [
        "",
        "## Labels",
        "",
        f"Two SMEs on {a['cases']} held-out cases: {a['disagreements']} disagreements, risk kappa {a['risk']:.2f}.",
        "",
        "| Flag | Cohen's kappa |",
        "|---|---|",
    ]
    md += [f"| {f} | {k:.2f} |" for f, k in a["flags"].items()]
    p = dev["production"]
    md += [
        "",
        "## Twelve production weeks (development seeds)",
        "",
        f"New typology from week 7; first alert week {p['first_alert_week']}; false-alert weeks before it "
        f"{p['false_alert_weeks']}; candidate promoted from week {p['promoted_week']}.",
        "",
        "| Week | Serving | Factual edits | Control limit | Case accuracy | Crypto recall | Alerts |",
        "|---|---|---|---|---|---|---|",
    ]
    for x in p["weeks"]:
        ucl = "" if x["edit_ucl"] != x["edit_ucl"] else f"{x['edit_ucl']:.1%}"
        cr = "" if x["crypto_recall"] is None else f"{x['crypto_recall']:.2f}"
        md.append(
            f"| {x['week']} | {x['config']} | {x['factual_edit_rate']:.1%} | {ucl} | {x['case_correct']:.3f} | {cr} | "
            f"{'; '.join(x['alerts'])} |"
        )
    dfl = dev["deflection"]
    md += [
        "",
        "## Upstream deflection",
        "",
        f"{dfl['customers']:,} new customers; trained on {dfl['train']:,}, tested on {dfl['test']:,} "
        f"({dfl['positives_test']} future high-risk cases). AUC {dfl['auc']:.3f} (rules {dfl['auc_rules']:.3f}).",
        "",
        "| Good customers asked for documents | Future high-risk cases caught (model) | (rules) |",
        "|---|---|---|",
    ]
    for m, r in zip(dfl["model"], dfl["rules"]):
        md.append(f"| {m['friction']:.1%} | {m['recall']:.1%} ({m['caught']}) | {r['recall']:.1%} ({r['caught']}) |")
    (ROOT / "RESULTS.md").write_text("\n".join(md) + "\n")
    print("wrote RESULTS.md and web/public/data/dashboard.json")


if __name__ == "__main__":
    main()
